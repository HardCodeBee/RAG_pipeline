#!/usr/bin/env python3
"""Build advisor-facing tables and figures for the retriever-policy report.

The script consumes only the BM25/Dense analysis generated by
``analyze_beir_retriever_policy.py`` and local BEIR manifests/query/qrels files.
It does not execute retrieval, reranking, model inference, or generation.
"""

